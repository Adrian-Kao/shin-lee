def _render_rejections_block(rejections: list[dict], start_offset: int = 0) -> str:
    """Render the rejection items section of a TIPO notice.

    start_offset shifts which Chinese ordinal label the first rejection uses.
    Initial OA: "(一) 本案標題..." is already printed by the caller, so pass
    start_offset=1 so rejections start at "(二)". Re-exam notices, which print
    their own "(一) 申復理由概述" lead-in, also pass start_offset=1.
    """
    out: list[str] = []
    indices = ["(一)", "(二)", "(三)", "(四)", "(五)", "(六)", "(七)"]
    for i, rej in enumerate(rejections):
        pos = i + start_offset
        idx = indices[pos] if pos < len(indices) else f"({pos+1})"
        claims_str = "、".join(str(c) for c in rej["affected_claims"])
        cited = "、".join(rej["cited_prior_art"]) if rej["cited_prior_art"] else "（無引證案）"
        out.append(f"    {idx} 本案請求項 {claims_str} 有不符 {rej['statute']} 之情形。")
        if rej["cited_prior_art"]:
            out.append(f"        引證資料：{cited}。")
        out.append(f"        {rej['argument']}")
        out.append("")
    return "\n".join(out)


